/** Пробовал ли ребёнок то, что стоит за ключом (null — отметки нет). */
function found(key, feats, flags) {
  if (!key) return null;
  if (key.startsWith('d:')) return !!flags.dreamTried?.[key.slice(2)];
  return (feats[key] || 0) > 0 || !!flags.tried?.[key];
}

const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

/** Раздел справки: группы по комнатам и мирам; у каждой строки отметка «пробовали / ещё нет». */
export function helpHtml(feats = {}, flags = {}) {
  return HELP.map(([title, items]) => {
    const marks = items.map(([key]) => found(key, feats, flags));
    const total = marks.filter((m) => m !== null).length;
    const done = marks.filter((m) => m === true).length;
    const rows = items.map(([, what, result], i) => {
      const m = marks[i];
      const mark = m === null ? '<i class="na">•</i>' : m ? '<i class="ok">✓</i>' : '<i class="no">○</i>';
      return `<li>${mark}<span><b>${esc(what)}</b> — ${esc(result)}</span></li>`;
    }).join('');
    return `<details data-help="${esc(title)}"><summary>${esc(title)}${total ? `<span>пробовали ${done} из ${total}</span>` : ''}</summary><ul class="help">${rows}</ul></details>`;
  }).join('');
}

/** Все ключи справки (для проверки, что каждая отметка чему-то соответствует). */
export const helpKeys = () => HELP.flatMap(([, items]) => items.map(([key]) => key).filter(Boolean));
